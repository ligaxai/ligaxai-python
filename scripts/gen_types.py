"""Regenerate ``src/ligaxai/_generated/models.py`` from ``openapi/openapi.json``.

Runs ``datamodel-codegen`` with this SDK's ``BaseModel`` as the base class so every
generated model carries ``request_id``. Exits 0 with a message when no spec has been synced
yet, so ``make gen-types`` is safe in a fresh clone.

``--check`` regenerates into a temporary file and fails if it differs from the committed
models — the drift guard that keeps ``_generated/`` honest against the pinned spec.

**Why the spec is normalised first.** The platform emits every body schema inline (its
generator uses Zod's ``reused: 'inline'``), with shared pieces in a per-body ``$defs`` and
references written as ``#/$defs/RunStatus``. In an OpenAPI document a ``#`` pointer
resolves against the *document* root, where no ``$defs`` exists, so the raw file cannot be
fed to a generator (datamodel-codegen answers "Models not found"). ``normalise`` hoists
each body and its ``$defs`` into ``components/schemas`` under a stable name
(``SCHEMA_NAMES``), rewrites the references, refuses two different bodies under one name,
and drops ``additionalProperties: false`` from response bodies — the generator would turn
it into ``extra="forbid"``, and an SDK must keep working when the server adds a field.
"""

from __future__ import annotations

import argparse
import copy
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "openapi" / "openapi.json"
OUT = ROOT / "src" / "ligaxai" / "_generated" / "models.py"
HEADER = "# generated by scripts/gen_types.py from openapi.json — do not edit\n"

# (operationId, "request" | status code) -> component name. Anything unlisted gets a name
# derived from the operation id, so a new endpoint still generates; name it here after.
SCHEMA_NAMES: dict[tuple[str, str], str] = {
    ("runs.create", "request"): "RunRequest",
    ("runs.create", "200"): "Run",
    ("runs.create", "202"): "Run",
    ("runs.get", "200"): "Run",
    ("runs.cancel", "200"): "Run",
    ("runs.resolveInterrupt", "200"): "Run",
    ("runs.resolveInterrupt", "request"): "InterruptResolution",
    ("runs.events", "200"): "RunEventList",
    ("conversations.get", "200"): "Conversation",
    ("profiles.list", "200"): "ProfileList",
    ("profiles.get", "200"): "Profile",
    ("keys.self", "200"): "ApiKey",
    ("usage.get", "200"): "UsageReport",
}

# Nested objects worth a public name: (component, property) -> new component. Without this
# the generator names them after the property (`Usage`, `Error`), and two different
# objects sharing a property name come out as `Usage` and `Usage1`. Order matters: a
# hoisted component can itself be the parent of a later row.
NESTED_NAMES: list[tuple[str, str, str]] = [
    ("Run", "output", "RunOutput"),
    ("Run", "required_action", "RequiredAction"),
    ("Run", "usage", "RunUsage"),
    ("Run", "error", "RunError"),
    ("RunOutput", "artifacts", "RunArtifact"),
    ("RunOutput", "sources", "RunSource"),
    ("RunOutput", "tool_calls", "RunToolCall"),
    ("Profile", "models", "ProfileModels"),
    ("Profile", "connectors", "ProfileConnector"),
    ("ApiKey", "limit", "ApiKeyLimit"),
    ("UsageReport", "data", "UsageBucket"),
]

# Counts the platform declares as `z.number()` (JSON Schema "number") that are integers by
# construction. Typed `int` here so `run.usage.input_tokens` reads 3057, not 3057.0;
# pydantic still accepts an integral float. `duration_ms` stays a float on purpose.
INTEGER_FIELDS = frozenset(
    {
        "seq",
        "index",
        "version",
        "input_tokens",
        "output_tokens",
        "model_calls",
        "rate_limit_per_minute",
    }
)


def _pascal(operation_id: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in operation_id.replace("-", ".").split("."))


def _rewrite_refs(node: Any) -> Any:
    if isinstance(node, dict):
        out: dict[str, Any] = {}
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str) and value.startswith("#/$defs/"):
                out[key] = "#/components/schemas/" + value.removeprefix("#/$defs/")
            else:
                out[key] = _rewrite_refs(value)
        return out
    if isinstance(node, list):
        return [_rewrite_refs(v) for v in node]
    return node


def _open_objects(node: Any) -> Any:
    """Drop ``additionalProperties: false`` everywhere (see module docstring)."""
    if isinstance(node, dict):
        return {
            k: _open_objects(v)
            for k, v in node.items()
            if not (k == "additionalProperties" and v is False)
        }
    if isinstance(node, list):
        return [_open_objects(v) for v in node]
    return node


def _drop_property_names(node: Any) -> Any:
    """Drop ``propertyNames``: the generator renders it as ``dict[constr(...), ...]``, a call
    in a type position that mypy and pyright both reject. The server still enforces it."""
    if isinstance(node, dict):
        return {k: _drop_property_names(v) for k, v in node.items() if k != "propertyNames"}
    if isinstance(node, list):
        return [_drop_property_names(v) for v in node]
    return node


def _is_plain_enum(schema: dict[str, Any]) -> bool:
    return set(schema) <= {"type", "enum", "description"} and "enum" in schema


def _inline_refs(node: Any, inline: dict[str, Any]) -> Any:
    """Replace ``#/$defs/<name>`` with the schema itself for every name in ``inline``."""
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/$defs/"):
            name = ref.removeprefix("#/$defs/")
            if name in inline:
                return copy.deepcopy(inline[name])
        return {k: _inline_refs(v, inline) for k, v in node.items()}
    if isinstance(node, list):
        return [_inline_refs(v, inline) for v in node]
    return node


def _integers(node: Any) -> Any:
    """Type the ``INTEGER_FIELDS`` properties as JSON Schema integers."""
    if isinstance(node, dict):
        out = {k: _integers(v) for k, v in node.items()}
        props = out.get("properties")
        if isinstance(props, dict):
            for key in INTEGER_FIELDS & props.keys():
                out["properties"][key] = _number_to_integer(props[key])
        return out
    if isinstance(node, list):
        return [_integers(v) for v in node]
    return node


def _number_to_integer(schema: Any) -> Any:
    if isinstance(schema, dict):
        if schema.get("type") == "number":
            return {**schema, "type": "integer"}
        if "anyOf" in schema:
            return {**schema, "anyOf": [_number_to_integer(s) for s in schema["anyOf"]]}
    return schema


def _hoist(schemas: dict[str, Any], parent: str, prop: str, name: str) -> None:
    """Move ``schemas[parent].properties[prop]``'s object schema to ``schemas[name]``."""
    holder = schemas[parent]["properties"]
    ref = {"$ref": f"#/components/schemas/{name}"}

    def take(node: dict[str, Any]) -> dict[str, Any]:
        if node.get("type") == "object":
            existing = schemas.get(name)
            if existing is not None and existing != node:
                raise SystemExit(f"gen_types: two different schemas want the name {name!r}")
            schemas[name] = node
            return ref
        if node.get("type") == "array" and isinstance(node.get("items"), dict):
            return {**node, "items": take(node["items"])}
        if "anyOf" in node:
            return {**node, "anyOf": [take(s) if isinstance(s, dict) else s for s in node["anyOf"]]}
        return node

    holder[prop] = take(holder[prop])


def normalise(spec: dict[str, Any]) -> dict[str, Any]:
    """Return a copy of ``spec`` whose bodies all live in ``components/schemas``."""
    doc = copy.deepcopy(spec)
    schemas: dict[str, Any] = doc.setdefault("components", {}).setdefault("schemas", {})

    def register(name: str, schema: dict[str, Any], *, response: bool) -> dict[str, str]:
        body = dict(schema)
        defs: dict[str, Any] = body.pop("$defs", None) or {}
        # A bare enum ($defs/RunStatus) is inlined, so the field is a `Literal` rather than a
        # `RootModel` — `run.status == "completed"` must be true for a completed run.
        enums = {k: v for k, v in defs.items() if _is_plain_enum(v)}
        body = _inline_refs(body, enums)
        for def_name, def_schema in defs.items():
            if def_name not in enums:
                register(def_name, _inline_refs(def_schema, enums), response=response)
        body = _drop_property_names(_integers(_rewrite_refs(body)))
        if response:
            body = _open_objects(body)
        existing = schemas.get(name)
        if existing is not None and existing != body:
            raise SystemExit(f"gen_types: two different schemas want the name {name!r}")
        schemas[name] = body
        return {"$ref": f"#/components/schemas/{name}"}

    for path_item in doc.get("paths", {}).values():
        for op in path_item.values():
            if not isinstance(op, dict) or "operationId" not in op:
                continue
            op_id: str = op["operationId"]
            media = ((op.get("requestBody") or {}).get("content") or {}).get("application/json")
            if media and "schema" in media:
                name = SCHEMA_NAMES.get((op_id, "request"), _pascal(op_id) + "Request")
                media["schema"] = register(name, media["schema"], response=False)
            for status, resp in (op.get("responses") or {}).items():
                media = (resp.get("content") or {}).get("application/json")
                if not media or "schema" not in media:
                    continue
                if status.startswith(("4", "5")):
                    # Errors surface as exceptions (`_exceptions.py`), never as parsed models,
                    # and the envelope's `request_id` field would collide with
                    # `BaseModel.request_id`. Left inline, so the generator skips them.
                    continue
                name = SCHEMA_NAMES.get((op_id, status), f"{_pascal(op_id)}Response{status}")
                media["schema"] = register(name, media["schema"], response=True)
    for parent, prop, name in NESTED_NAMES:
        if parent in schemas and prop in schemas[parent].get("properties", {}):
            _hoist(schemas, parent, prop, name)
    return doc


def generate(out: Path) -> None:
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        normalised = Path(tmp) / "openapi.json"
        normalised.write_text(json.dumps(normalise(spec), indent=2), encoding="utf-8")
        cmd = [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(normalised),
            "--input-file-type",
            "openapi",
            "--output",
            str(out),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--base-class",
            "ligaxai._models.BaseModel",
            "--target-python-version",
            "3.11",
            "--use-standard-collections",
            "--use-union-operator",
            "--use-schema-description",
            "--field-constraints",
            "--snake-case-field",
            "--enum-field-as-literal",
            "all",
            "--formatters",
            "builtin",
            "--disable-timestamp",
        ]
        proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
        if proc.returncode != 0:
            print(proc.stdout, proc.stderr, sep="\n")
            raise SystemExit(f"gen_types: datamodel-codegen failed ({proc.returncode})")
    body = out.read_text(encoding="utf-8")
    if not body.startswith(HEADER):
        body = HEADER + body
    # Format as if the file sat at its real path, so `--check` (which writes to a temporary
    # directory) and `make gen-types` resolve the same ruff configuration.
    fmt = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "format",
            "--stdin-filename",
            str(OUT.relative_to(ROOT)),
            "-",
        ],
        input=body,
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=True,
    )
    out.write_text(fmt.stdout, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check", action="store_true", help="fail if the committed models are stale"
    )
    args = parser.parse_args()
    if not SPEC.exists():
        print(f"gen_types: {SPEC.relative_to(ROOT)} not found — run `make sync-spec` first.")
        return 0
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            fresh = Path(tmp) / "models.py"
            generate(fresh)
            if fresh.read_text(encoding="utf-8") != OUT.read_text(encoding="utf-8"):
                print(
                    "gen_types: src/ligaxai/_generated/models.py is stale against "
                    "openapi/openapi.json — run `make gen-types` and commit the result."
                )
                return 1
        print("gen_types: generated models match openapi/openapi.json")
        return 0
    generate(OUT)
    print(f"gen_types: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
