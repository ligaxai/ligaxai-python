"""Regenerate ``src/ligaxai/_generated/models.py`` from ``openapi/openapi.json``.

Runs ``datamodel-codegen`` with this SDK's ``BaseModel`` as the base class so every
generated model carries ``request_id``. Exits 0 with a message when no spec has been synced
yet, so ``make gen-types`` is safe in a fresh clone.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "openapi" / "openapi.json"
OUT = ROOT / "src" / "ligaxai" / "_generated" / "models.py"
HEADER = "# generated by scripts/gen_types.py from openapi.json — do not edit\n"


def main() -> int:
    if not SPEC.exists():
        print(f"gen_types: {SPEC.relative_to(ROOT)} not found — run `make sync-spec` first.")
        return 0
    cmd = [
        sys.executable,
        "-m",
        "datamodel_code_generator",
        "--input",
        str(SPEC),
        "--input-file-type",
        "openapi",
        "--output",
        str(OUT),
        "--output-model-type",
        "pydantic_v2.BaseModel",
        "--base-class",
        "ligaxai._models.BaseModel",
        "--target-python-version",
        "3.11",
        "--use-standard-collections",
        "--use-union-operator",
        "--use-schema-description",
        "--field-constraints",
        "--snake-case-field",
        "--disable-timestamp",
    ]
    print("gen_types:", " ".join(cmd[2:]))
    subprocess.run(cmd, check=True)
    body = OUT.read_text()
    if not body.startswith(HEADER):
        OUT.write_text(HEADER + body)
    print(f"gen_types: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
